def _get_created_process_details(
    client: httpx.Client,
    settings: Settings,
    access_token: str,
    api_key: str,
    org_id: str,
    process_ids: list[str],
) -> list[dict[str, Any]]:
    details: list[dict[str, Any]] = []
    for process_id in process_ids:
        response = _request(
            client,
            "Get KEDO signing process",
            "GET",
            _api_path(settings, f"/kedo/api/v1/orgs/{org_id}/processes/{process_id}"),
            headers=_json_headers(access_token, api_key),
            params={"flat": False, "includeCandidateTargets": False},
        )
        payload = response.json()
        if not isinstance(payload, dict):
            raise KedoApiError(
                "Get KEDO signing process",
                502,
                "Unexpected non-object process response.",
            )
        details.append(dict(payload))
    return details


def _check_created_document_downloads(
    settings: Settings,
    *,
    access_token: str,
    process_id: str | None,
    document_id: str | None,
    content_location: str | None,
) -> list[KedoDownloadCheck]:
    checks: list[KedoDownloadCheck] = []
    if content_location:
        checks.append(
            _download_check(
                "contents",
                lambda: download_content(
                    settings,
                    access_token=access_token,
                    file_id=content_location,
                ),
            )
        )
    if process_id and document_id:
        checks.append(
            _download_check(
                "print",
                lambda: download_document_print(
                    settings,
                    access_token=access_token,
                    process_id=process_id,
                    document_id=document_id,
                ),
            )
        )
    return checks


def _download_check(method: str, download: Callable[[], KedoDownloadedFile]) -> KedoDownloadCheck:
    try:
        file = download()
    except KedoApiError as error:
        return KedoDownloadCheck(
            method=method,
            ok=False,
            status_code=error.status_code,
            message=error.response_text,
        )

    return KedoDownloadCheck(
        method=method,
        ok=bool(file.content),
        status_code=200,
        size=len(file.content),
        content_type=file.content_type,
        message=None if file.content else "Empty file.",
    )


def _download_content(
    client: httpx.Client,
    settings: Settings,
    access_token: str,
    api_key: str,
    org_id: str,
    file_id: str,
    file_name: str,
) -> KedoDownloadedFile:
    response = _request(
        client,
        "Download KEDO content",
        "GET",
        _api_path(settings, f"/kedo/api/v1/orgs/{org_id}/contents/{file_id}"),
        headers=_download_headers(access_token, api_key),
    )
    return KedoDownloadedFile(
        content=response.content,
        content_type=response.headers.get("content-type", "application/octet-stream"),
        file_name=file_name,
    )


def _download_document_print(
    client: httpx.Client,
    settings: Settings,
    access_token: str,
    api_key: str,
    org_id: str,
    process_id: str,
    document_id: str,
) -> bytes:
    response = _request(
        client,
        "Start KEDO document print",
        "POST",
        _api_path(
            settings,
            f"/kedo/api/v1/orgs/{org_id}/processes/{process_id}/documents/{document_id}/print/tasks",
        ),
        headers=_json_headers(access_token, api_key),
    )
    payload = _wait_for_print_result(
        client,
        settings,
        access_token,
        api_key,
        org_id,
        process_id,
        document_id,
        response.json(),
    )
    encoded_bytes = _string_value(payload, "bytes")
    if encoded_bytes is None:
        raise KedoApiError("Download KEDO document print", 502, "Print result is empty.")
    try:
        return base64.b64decode(encoded_bytes, validate=True)
    except binascii.Error as error:
        raise KedoApiError(
            "Download KEDO document print", 502, "Print result is not valid base64."
        ) from error


def _wait_for_print_result(
    client: httpx.Client,
    settings: Settings,
    access_token: str,
    api_key: str,
    org_id: str,
    process_id: str,
    document_id: str,
    task_payload: Any,
    *,
    timeout_seconds: float = 60.0,
    poll_interval_seconds: float = 1.0,
) -> dict[str, Any]:
    if not isinstance(task_payload, dict):
        raise KedoApiError("Download KEDO document print", 502, "Unexpected print response.")

    task_id = _string_value(task_payload, "taskId") or _string_value(task_payload, "id")
    started_at = perf_counter()
    payload = task_payload
    while True:
        status = _string_value(payload, "status")
        if status == "Complete":
            return payload

        if status in {"Failed", "Unknown"}:
            raise KedoApiError("Download KEDO document print", 422, status)

        if not task_id:
            raise KedoApiError("Download KEDO document print", 502, "Task id is missing.")
        if perf_counter() - started_at >= timeout_seconds:
            raise KedoApiError("Download KEDO document print", 504, "Print task timed out.")

        sleep(poll_interval_seconds)
        response = _request(
            client,
            "Get KEDO document print result",
            "POST",
            _api_path(
                settings,
                f"/kedo/api/v1/orgs/{org_id}/processes/{process_id}/documents/{document_id}/print/tasks/{task_id}",
            ),
            headers=_json_headers(access_token, api_key),
        )
        payload = response.json()
        if not isinstance(payload, dict):
            raise KedoApiError("Download KEDO document print", 502, "Unexpected print response.")


def _process_ids(processes: list[dict[str, Any]]) -> list[str]:
    return [
        process_id
        for process in processes
        if (process_id := _string_value(process, "id")) is not None
    ]


def _process_document_ids(processes: list[dict[str, Any]]) -> list[str]:
    document_ids: list[str] = []
    for document in _iter_process_documents(processes):
        document_id = _string_value(document, "id")
        if document_id:
            document_ids.append(document_id)
    return document_ids


def _draft_document_ids(processes: list[dict[str, Any]]) -> list[str]:
    draft_ids: list[str] = []
    for document in _iter_process_documents(processes):
        if document.get("isDraft") is not True:
            continue
        draft_ids.append(_string_value(document, "id") or str(document.get("documentKey") or "?"))
    return draft_ids


def _iter_process_documents(processes: list[dict[str, Any]]) -> Iterable[dict[str, Any]]:
    for process in processes:
        documents = process.get("documents")
        if isinstance(documents, dict):
            for document in documents.values():
                if isinstance(document, dict):
                    yield document

        flat_documents = process.get("flatDocuments")
        if isinstance(flat_documents, list):
            for document in flat_documents:
                if isinstance(document, dict):
                    yield document


def _signature_types(settings: Settings) -> list[str]:
    return [
        signature_type.strip()
        for signature_type in settings.kedo_signature_types.split(",")
        if signature_type.strip()
    ] or ["Pep"]


def _normalize_organization(item: dict[str, Any]) -> KedoOrganization:
    return KedoOrganization(
        id=_required_string(item, "id"),
        name=_string_value(item, "name"),
        short_name=_string_value(item, "shortName"),
        inn=_string_value(item, "inn"),
        kpp=_string_value(item, "kpp"),
    )


def _normalize_employee(item: dict[str, Any]) -> KedoEmployee:
    user = item.get("user")
    user_payload = user if isinstance(user, dict) else {}
    full_name = " ".join(
        value
        for value in (
            _string_value(user_payload, "lastName"),
            _string_value(user_payload, "firstName"),
            _string_value(user_payload, "middleName"),
        )
        if value
    )

    return KedoEmployee(
        id=_required_string(item, "id"),
        org_id=_string_value(item, "orgId"),
        user_id=_string_value(item, "userId"),
        full_name=full_name or None,
        login=_string_value(user_payload, "login"),
    )


def _normalize_document_type(item: dict[str, Any]) -> KedoDocumentType:
    metadata = item.get("metadata")
    metadata_payload = metadata if isinstance(metadata, dict) else {}

    return KedoDocumentType(
        id=_required_string(item, "id"),
        name=_string_value(item, "name"),
        is_default=bool(item.get("isDefault")),
        is_disabled=bool(item.get("isDisabled")),
        is_formalized=bool(metadata_payload.get("isFormalized")),
        metadata=metadata_payload,
    )


def _paged_result(payload: Any) -> list[dict[str, Any]]:
    if not isinstance(payload, dict):
        return []
    result = payload.get("result")
    if not isinstance(result, list):
        return []
    return [item for item in result if isinstance(item, dict)]


def _as_object_list(payload: Any) -> list[dict[str, Any]]:
    if isinstance(payload, list):
        return [item for item in payload if isinstance(item, dict)]
    if isinstance(payload, dict):
        return [payload]
    return []


def _required_string(payload: dict[str, Any], key: str) -> str:
    value = _string_value(payload, key)
    if value is None:
        raise KedoAuthError(f"KEDO response does not contain required field {key}.")
    return value


def _string_value(payload: dict[str, Any], key: str) -> str | None:
    value = payload.get(key)
    return value if isinstance(value, str) and value else None


def _raise_for_status(response: httpx.Response, stage: str) -> None:
    if response.is_success:
        return
    raise KedoApiError(stage, response.status_code, response.text.strip())


def _request(
    client: httpx.Client,
    stage: str,
    method: str,
    url: str,
    **kwargs: Any,
) -> httpx.Response:
    try:
        response = client.request(method, url, **kwargs)
    except httpx.HTTPError as error:
        raise KedoApiError(stage, 0, f"{type(error).__name__}: {error}") from error

    _raise_for_status(response, stage)
    return response


def _json_headers(access_token: str, api_key: str) -> dict[str, str]:
    return {
        "Accept": "application/json",
        "Authorization": f"Bearer {access_token}",
        "X-Kontur-ApiKey": api_key,
    }


def _download_headers(access_token: str, api_key: str) -> dict[str, str]:
    return {
        "Accept": "application/octet-stream",
        "Authorization": f"Bearer {access_token}",
        "X-Kontur-ApiKey": api_key,
    }


def _api_key(settings: Settings) -> str:
    api_key = settings.kedo_api_key or settings.client_secret or settings.api_key
    if not api_key:
        raise KedoAuthError(
            "KONTUR_KEDO_API_KEY, KONTUR_CLIENT_SECRET or KONTUR_API_KEY must be configured."
        )
    return api_key


def _base_url(settings: Settings) -> str:
    return str(settings.kedo_base_url).rstrip("/")


def _api_path(settings: Settings, path: str) -> str:
    base_path = urlparse(_base_url(settings)).path.rstrip("/").casefold()
    if base_path.endswith("/kedo") and path.startswith("/kedo/"):
        return path.removeprefix("/kedo")
    return path
