def send_test_document(
    settings: Settings,
    *,
    access_token: str | None = None,
    document_type_id: str | None = None,
    sender_id: str | None = None,
    employee_id: str | None = None,
    signature_type: str | None = None,
    due_days: int | None = None,
    file_name: str | None = None,
    file_bytes: bytes | None = None,
) -> KedoTestDocumentResponse:
    token = access_token or authenticate_with_password(settings)
    api_key = _api_key(settings)

    with httpx.Client(base_url=_base_url(settings), timeout=60.0) as client:
        org_id = settings.kedo_org_id or _get_first_organization(
            client, settings, token, api_key
        ).id
        employee_id = employee_id or settings.kedo_employee_id or _get_current_employee(
            client, settings, token, api_key, org_id
        ).id
        sender_id = sender_id or employee_id
        document_type_id = document_type_id or settings.kedo_document_type_id
        document_type_id = document_type_id or _get_document_type(
            client,
            settings,
            token,
            api_key,
            org_id,
        ).id

        file_name = file_name or settings.kedo_test_filename or TEST_DOCUMENT_FILENAME
        content = _upload_content(
            client,
            settings,
            token,
            api_key,
            org_id,
            file_name,
            file_bytes if file_bytes is not None else _test_document_bytes(settings, file_name),
        )
        content["name"] = file_name

        processed_content = _process_content(
            client,
            settings,
            token,
            api_key,
            org_id,
            document_type_id,
            content,
        )
        processed_content["name"] = processed_content.get("name") or file_name

        process_payload = _build_process_payload(
            settings,
            sender_id=sender_id,
            employee_id=employee_id,
            document_type_id=document_type_id,
            content=processed_content,
            signature_type=signature_type,
            due_days=due_days,
        )
        processes_response = _request(
            client,
            "Create KEDO signing process",
            "POST",
            _api_path(settings, f"/kedo/api/v1/orgs/{org_id}/processes"),
            params={"flat": False},
            headers=_json_headers(token, api_key),
            json=process_payload,
        )

        raw_processes = _as_object_list(processes_response.json())
        process_ids = _process_ids(raw_processes)
        process_details = _get_created_process_details(
            client,
            settings,
            token,
            api_key,
            org_id,
            process_ids,
        )

    validated_processes = process_details or raw_processes
    document_ids = _process_document_ids(validated_processes)
    if not document_ids:
        raise KedoApiError(
            "Validate KEDO signing process",
            502,
            "Created process does not contain documents.",
        )

    draft_document_ids = _draft_document_ids(validated_processes)
    if draft_document_ids:
        raise KedoApiError(
            "Validate KEDO signing process",
            422,
            f"Created document is still a draft: {', '.join(draft_document_ids)}.",
        )

    return KedoTestDocumentResponse(
        org_id=org_id,
        employee_id=employee_id,
        document_type_id=document_type_id,
        file_name=file_name,
        content_location=_string_value(content, "location"),
        processed_content_location=_string_value(processed_content, "location"),
        process_ids=process_ids,
        document_ids=document_ids,
        raw_response=raw_processes,
        request_payload=process_payload,
        process_details=process_details,
        download_checks=[],
    )


def check_connectivity(settings: Settings, *, timeout: float = 10.0) -> KedoConnectivityResponse:
    started_at = perf_counter()
    parsed_url = urlparse(_base_url(settings))
    host = parsed_url.hostname or ""
    port = parsed_url.port or 443
    resolved_addresses: list[str] = []
    dns_error: str | None = None
    tcp_error: str | None = None
    tls_error: str | None = None
    tcp_connected = False
    tls_connected = False
    tls_version: str | None = None

    try:
        resolved_addresses = sorted(
            {
                address[4][0]
                for address in socket.getaddrinfo(host, port, type=socket.SOCK_STREAM)
                if isinstance(address[4][0], str)
            }
        )
    except OSError as error:
        dns_error = f"{type(error).__name__}: {error}"

    try:
        with socket.create_connection((host, port), timeout=timeout) as raw_socket:
            tcp_connected = True
            context = ssl.create_default_context()
            with context.wrap_socket(raw_socket, server_hostname=host) as tls_socket:
                tls_connected = True
                tls_version = tls_socket.version()
    except (OSError, TimeoutError, ssl.SSLError) as error:
        error_message = f"{type(error).__name__}: {error}"
        if tcp_connected:
            tls_error = error_message
        else:
            tcp_error = error_message

    return KedoConnectivityResponse(
        url=_base_url(settings),
        host=host,
        port=port,
        resolved_addresses=resolved_addresses,
        dns_error=dns_error,
        tcp_connected=tcp_connected,
        tcp_error=tcp_error,
        tls_connected=tls_connected,
        tls_version=tls_version,
        tls_error=tls_error,
        elapsed_ms=round((perf_counter() - started_at) * 1000),
    )


def _test_document_bytes(settings: Settings, file_name: str) -> bytes:
    if settings.kedo_test_text:
        return settings.kedo_test_text.encode("utf-8")
    if file_name.casefold().endswith(".pdf"):
        return _build_pdf_bytes("Test document for Kontur KEDO signing.")
    return TEST_DOCUMENT_TEXT.encode("utf-8")


def _build_pdf_bytes(text: str) -> bytes:
    escaped_text = text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    escaped_text = escaped_text.encode("ascii", errors="replace").decode("ascii")
    stream = f"BT /F1 18 Tf 72 760 Td ({escaped_text}) Tj ET\n".encode("ascii")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>\n",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>\n",
        (
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
            b"/Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>\n"
        ),
        (
            b"<< /Length "
            + str(len(stream)).encode("ascii")
            + b" >>\nstream\n"
            + stream
            + b"endstream\n"
        ),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\n",
    ]

    chunks = [b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n"]
    offsets: list[int] = []
    for index, pdf_object in enumerate(objects, start=1):
        offsets.append(sum(len(chunk) for chunk in chunks))
        chunks.append(f"{index} 0 obj\n".encode("ascii") + pdf_object + b"endobj\n")

    xref_offset = sum(len(chunk) for chunk in chunks)
    xref_rows = [b"0000000000 65535 f \n"]
    xref_rows.extend(f"{offset:010d} 00000 n \n".encode("ascii") for offset in offsets)
    chunks.extend(
        [
            b"xref\n",
            f"0 {len(objects) + 1}\n".encode("ascii"),
            *xref_rows,
            b"trailer\n",
            f"<< /Size {len(objects) + 1} /Root 1 0 R >>\n".encode("ascii"),
            b"startxref\n",
            f"{xref_offset}\n".encode("ascii"),
            b"%%EOF\n",
        ]
    )
    return b"".join(chunks)


def authenticate_with_password(settings: Settings) -> str:
    login = settings.kedo_login or settings.login
    password = settings.kedo_password or settings.password
    if not login or not password:
        raise KedoAuthError(
            "KONTUR_LOGIN and KONTUR_PASSWORD must be configured or user must sign in."
        )

    api_key = _api_key(settings)
    with httpx.Client(base_url=_base_url(settings), timeout=30.0) as client:
        response = _request(
            client,
            "KEDO password authentication",
            "POST",
            _api_path(settings, "/kedo/api/v1/authenticate"),
            headers={
                "Accept": "application/json",
                "Content-Type": "application/json",
                "X-Kontur-ApiKey": api_key,
            },
            json={
                "requestType": "Login",
                "login": login,
                "password": password,
            },
        )

    payload = response.json()
    access_token = payload.get("accessToken") if isinstance(payload, dict) else None
    if not isinstance(access_token, str) or not access_token:
        raise KedoAuthError("KEDO authentication response does not contain accessToken.")

    return access_token


